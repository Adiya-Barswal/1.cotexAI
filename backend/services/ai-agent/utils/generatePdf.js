import PDFDocument from "pdfkit";

export const generatePdf = async (data) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: "A4",
        margin: 50,
        info: {
          Author: "CortexAI",
          Title: data.title,
          Creator: "CortexAI",
        },
      });

      const chunks = [];

      // Collect PDF data chunks
      doc.on("data", (chunk) => chunks.push(chunk));

      // Return the completed PDF as a Buffer
      doc.on("end", () => resolve(Buffer.concat(chunks)));

      // Reject if PDF generation fails
      doc.on("error", reject);

      // Document title
      doc.fillColor("#111827").fontSize(28).text(data.title, {
        align: "center",
      });

      // Subtitle
      if (data.subtitle) {
        doc.moveDown(0.5);
        doc.fillColor("#6B7280").fontSize(12).text(data.subtitle, {
          align: "center",
        });
      }

      doc.moveDown(2);

      // Document sections
      data.sections.forEach((section) => {
        doc.fillColor("#111827").fontSize(18).text(section.heading);

        doc.moveDown(0.5);

        section.points.forEach((point) => {
          doc.fillColor("#374151").fontSize(12).text(`- ${point}`, {
            lineGap: 5,
            paragraphGap: 2,
          });
        });

        doc.moveDown();
      });

      // Footer
      doc.moveDown();
      doc.fillColor("#9CA3AF").fontSize(10).text("Generated By CortexAI", {
        align: "center",
      });

      // Finish creating the PDF
      doc.end();
    } catch (error) {
      reject(error);
    }
  });
};
